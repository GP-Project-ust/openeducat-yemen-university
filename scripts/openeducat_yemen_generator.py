def phase7_fees(odoo, rep, manifest, plan, cfg, rng, names, counters):
    rep.log('— المرحلة 7: الرسوم الدراسية')
    _load_maps(odoo, plan, counters)
    if 'students' not in counters:
        counters['students'] = _load_students(odoo, counters)
    students, cmap, bmap = (counters['students'], counters['courses'],
                            counters['batches'])
    product_id = _ensure_service_product(odoo, rep, manifest)
    ftmap, created = get_or_create(odoo, rep, manifest, 'op.fees.terms',
                                   'name', [dict(
                                       name='دفعات فصلية (50% + 50%)',
                                       fees_terms='fixed_days',
                                       line_ids=[(0, 0, dict(due_days=0, value=50.0)),
                                                 (0, 0, dict(due_days=90, value=50.0))])])
    rep.log('   جدول الدفعات: %d (جديد: %d)' % (len(ftmap), created))
    # أسطر الدفعات تُنشأ داخلياً — نسجيلها في الـmanifest لضمان حذفها لاحقاً
    line_ids = odoo.search('op.fees.terms.line',
                           [('fees_id', 'in', list(ftmap.values()))])
    if line_ids:
        manifest.add('op.fees.terms.line', line_ids)
    prog_of_batch = {b['code']: b['program'] for b in plan['batches']}
    fees_dates = []
    for k in range(cfg['fees_years_back']):
        y = cfg['end_year'] - k
        fees_dates.append((y, '%d-10-05' % y, '%d-03-05' % (y + 1)))
    all_dates = [d for _, d1, d2 in fees_dates for d in (d1, d2)]
    existing = set()
    sids = [s['sid'] for s in students]
    for i in range(0, len(sids), 500):
        for rec in odoo.search_read(
                'op.student.fees.details',
                [('student_id', 'in', sids[i:i + 500]),
                 ('date', 'in', all_dates)], ['student_id', 'date']):
            existing.add((rec['student_id'][0], rec['date']))
    fee_vals = []
    for s in students:
        p = prog_of_batch.get(s['batch'])
        if not p:
            continue
        amount = round(p['fee'] / 2.0, 2)
        for y, d1, d2 in fees_dates:
            for d in (d1, d2):
                if (s['sid'], d) in existing:
                    continue
                fee_vals.append(dict(
                    student_id=s['sid'], product_id=product_id,
                    course_id=cmap[p['code']], batch_id=bmap[s['batch']],
                    amount=amount, date=d, state='draft'))
    ids, fail = safe_create(odoo, rep, manifest, 'op.student.fees.details',
                            fee_vals)
    rep.log('   سجلات الدفعات: %d (جديد: %d، إخفاق: %d)'
            % (len(fee_vals), len(ids), fail))
    rep.log('   ملاحظة: الفواتير المحاسبية تُنشأ من واجهة OpenEduCat زر الفاتورة')
    return ftmap


