_BATCH_WARNED = set()


def safe_create(odoo, rep, manifest, model, vals_list, batch=None):
    """إنشاء دفعات مع تراجع فردي: سجلٌّ معطوب لا يُسقط الدفعة كلها.

    يعيد (المعرّفات المنشأة، عدد الإخفاقات). ويسجّل المعرفات في الـmanifest.
    """
    if isinstance(vals_list, dict):
        vals_list = [vals_list]
    if not vals_list:
        return [], 0
    batch = batch or odoo.cfg['rpc_batch']
    ids, failures = [], 0
    batch_drops = 0
    for i in range(0, len(vals_list), batch):
        chunk = vals_list[i:i + batch]
        try:
            got = odoo.create(model, chunk)
            ids.extend(got if isinstance(got, list) else [got])
        except xmlrpc.client.Fault as e:
            batch_drops += 1
            if model not in _BATCH_WARNED:
                _BATCH_WARNED.add(model)
                rep.warn('النموذج %s غير آمن للإنشاء المجمع على هذا الخادم '
                         '(قيوده تفترض سجلاً واحداً) — سيُنشأ سجلاً سجلاً: %s'
                         % (model, str(e)[:150]))
            for vals in chunk:
                try:
                    got = odoo.create(model, vals)
                    ids.extend(got if isinstance(got, list) else [got])
                except xmlrpc.client.Fault as e2:
                    failures += 1
                    if failures <= 5:
                        rep.warn('إخفاق سجل واحد في %s: %s'
                                 % (model, str(e2)[:160]))
    if batch_drops:
        rep.log('   %s: %d دفعة تحولت لإنشاء فردي (%d سجلاً)'
                % (model, batch_drops, len(vals_list)))
    manifest.add(model, ids)
    return ids, failures


def get_or_create(odoo, rep, manifest, model, key_field, records,
                  extra_domain=()):
    """استئناف آمن: يجد الموجود بمفتاحه ويضيف الناقص فقط.

    records: قائمة dict تحتوي المفتاح وبقية القيم.
    يعيد (خريطة مفتاح -> id، عدد المنشأ حديثاً).
    """
    if not records:
        return {}, 0
    keys = [r[key_field] for r in records]
    mapping, created = {}, 0
    # البحث عن الموجود على دفعات (لأن بحث IN ضخم قد يثقل الخادم)
    CH = 500
    for i in range(0, len(keys), CH):
        chunk = keys[i:i + CH]
        found = odoo.search_read(
            model, [(key_field, 'in', chunk)] + list(extra_domain),
            [key_field])
        for rec in found:
            mapping[rec[key_field]] = rec['id']
    missing = [r for r in records if r[key_field] not in mapping]
    if missing:
        ids, _fail = safe_create(odoo, rep, manifest, model, missing)
        # بعد الإنشاء نقرأ المفاتيح لتأسيس الخريطة بدقة
        new_keys = [r[key_field] for r in missing]
        for i in range(0, len(new_keys), CH):
            chunk = new_keys[i:i + CH]
            found = odoo.search_read(
                model, [(key_field, 'in', chunk)] + list(extra_domain),
                [key_field])
            for rec in found:
                mapping[rec[key_field]] = rec['id']
        created = len(ids)
    return mapping, created


class Manifest:
    """سجل بكل المعرفات المنشأة — أساس الحذف العكسي الآمن (--purge)."""

    def __init__(self, path):
        self.path = path
        self.data = {'created': {}}
        if os.path.exists(path):
            try:
                with open(path, encoding='utf-8') as fh:
                    self.data = json.load(fh)
            except (ValueError, OSError):
                pass

    def add(self, model, ids):
        self.data['created'].setdefault(model, [])
        self.data['created'][model].extend(int(i) for i in ids)
        self.save()

    def save(self):
        tmp = self.path + '.tmp'
        with open(tmp, 'w', encoding='utf-8') as fh:
            json.dump(self.data, fh, ensure_ascii=False)
        os.replace(tmp, self.path)


def chunked(seq, size):
    for i in range(0, len(seq), size):
        yield seq[i:i + size]


