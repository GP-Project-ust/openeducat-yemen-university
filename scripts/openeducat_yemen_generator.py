def build_plan(cfg, rng):
    years = []
    for y in range(cfg['start_year'], cfg['end_year'] + 1):
        years.append(dict(
            year=y, name='%d/%02d' % (y, (y + 1) % 100),
            start='%d-09-01' % y, end='%d-08-31' % (y + 1),
            sem1=dict(name='الفصل الأول %d/%02d' % (y, (y + 1) % 100),
                      start='%d-09-20' % y, end='%d-01-25' % (y + 1)),
            sem2=dict(name='الفصل الثاني %d/%02d' % (y, (y + 1) % 100),
                      start='%d-02-05' % (y + 1), end='%d-06-20' % (y + 1)),
        ))
    # توزيع الطلاب: وزن البرنامج × نمو سنوي واقعي للقبول
    total_w = sum(PROGRAM_WEIGHTS.values())
    year_split = [0.85, 0.93, 1.0, 1.07, 1.15]
    norm = sum(year_split)
    batches = []
    for prog in PROGRAMS:
        ptotal = cfg['target_students'] * PROGRAM_WEIGHTS[prog['code']] / total_w
        for idx, y in enumerate(range(cfg['start_year'], cfg['end_year'] + 1)):
            n = int(round(ptotal * year_split[idx] / norm))
            batches.append(dict(
                program=prog, intake=y,
                code='%s-%d' % (prog['code'], y % 100),
                name=('دفعة %d - %s' % (y, prog['short']))[:32],
                start='%d-09-15' % y,
                end='%d-06-30' % (y + prog['years']),
                n_students=n))
    exam_years = list(range(cfg['end_year'] - cfg['exam_years_back'] + 1,
                            cfg['end_year'] + 1))
    n_sessions = 0
    for b in batches:
        for yA in exam_years:
            sy = yA - b['intake'] + 1
            if 1 <= sy <= b['program']['years']:
                n_sessions += 1
    n_ms_sessions = 0
    for b in batches:
        sy = cfg['end_year'] - b['intake'] + 1
        if 1 <= sy <= b['program']['years']:
            n_ms_sessions += 1
    total_students = sum(b['n_students'] for b in batches)
    plan = dict(
        years=years, batches=batches, exam_years=exam_years,
        n_sessions=n_sessions, n_ms_sessions=n_ms_sessions,
        total_students=total_students,
        n_subjects=sum(len(_subjects_of(p)) for p in PROGRAMS),
        n_admissions=int(total_students * (1 + cfg['rejected_ratio'])),
        n_exams=n_sessions * 6,
        n_attendees=int(n_sessions * (total_students / max(1, len(batches)))
                        * cfg['attendance_fraction']),
        n_mslines=int(n_ms_sessions * (total_students / max(1, len(batches)))),
        n_fees=int(total_students * 2 * cfg['fees_years_back']),
    )
    plan['rows_estimate'] = (
        total_students * 2 + plan['n_admissions'] + plan['n_subjects']
        + plan['n_attendees'] + plan['n_mslines'] * 7 + plan['n_fees']
        + 120 + 250 + 20)
    return plan


def _subjects_of(prog):
    """قائمة مواد البرنامج (سنة 1 من المشترك + بقية السنوات)."""
