PURGE_ORDER = [
    'op.result.line', 'op.marksheet.line', 'op.marksheet.register',
    'op.result.template',
    'op.grade.configuration', 'op.exam.attendees', 'op.exam',
    'op.exam.session', 'op.exam.type', 'op.student.fees.details',
    'op.fees.terms.line', 'op.fees.terms', 'op.admission',
    'op.admission.register', 'op.student.course', 'op.student', 'op.faculty',
    'op.batch', 'op.subject', 'op.course', 'op.department',
    'op.academic.term', 'op.academic.year', 'product.product',
]


def run_purge(odoo, rep, manifest):
    rep.log('حذف السجلات التي أنشأها السكريبت (ترتيب عكسي للتبعيات)...')
    created = manifest.data.get('created', {})
    if not any(created.values()):
        raise SystemExit('الـmanifest فارغ — لا يوجد ما يحذفه هذا السكريبت')
    for model in PURGE_ORDER:
        ids = created.get(model) or []
        if not ids:
            continue
        # التحقق من الوجود ثم الحذف على دفعات
        alive = odoo.search(model, [('id', 'in', ids)])
        n = 0
        for i in range(0, len(alive), 100):
            chunk = alive[i:i + 100]
            try:
                odoo.call(model, 'unlink', chunk)
                n += len(chunk)
            except xmlrpc.client.Fault as e:
                rep.warn('تعذر حذف %d سجل من %s: %s'
                         % (len(chunk), model, str(e)[:140]))
        rep.log('   %s: حُذف %d من %d' % (model, n, len(ids)))
        created[model] = []
    manifest.save()
    rep.log('اكتمل الحذف العكسي — القاعدة نظيفة من بيانات هذا السكريبت')


