def _ensure_service_product(odoo, rep, manifest):
    got = odoo.search_read('product.product', [('type', '=', 'service')],
                           ['id'], limit=1)
    if got:
        rep.log('   استخدام منتج خدمي قائم: id=%s' % got[0]['id'])
        return got[0]['id']
    for type_key in ('type', 'detailed_type'):
        try:
            pid = odoo.create('product.product', dict(
                name='الرسوم الدراسية', list_price=600000.0,
                **{type_key: 'service'}))
            if isinstance(pid, list):
                pid = pid[0]
            manifest.add('product.product', [pid])
            rep.log('   تم إنشاء منتج خدمي "الرسوم الدراسية" id=%s' % pid)
            return pid
        except xmlrpc.client.Fault:
            continue
    raise RuntimeError(
        'لا يوجد منتج خدمي ولا يمكن إنشاؤه — فعّل وحدة المنتجات (product)')


