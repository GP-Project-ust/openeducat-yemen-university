def merge_config(args):
    cfg = dict(CONFIG)
    cfg.update({k: v for k, v in PRESETS[args.preset].items()})
    if args.target is not None:
        cfg['target_students'] = args.target
    if args.start_year is not None:
        cfg['start_year'] = args.start_year
    if args.end_year is not None:
        cfg['end_year'] = args.end_year
    if args.batch_size is not None:
        cfg['rpc_batch'] = args.batch_size
    if args.exam_years_back is not None:
        cfg['exam_years_back'] = args.exam_years_back
    if args.attendance_fraction is not None:
        cfg['attendance_fraction'] = args.attendance_fraction
    if args.no_marksheets:
        cfg['marksheets'] = False
    if args.no_fees:
        cfg['fees'] = False
    cfg['url'] = (args.url or '').rstrip('/')
    cfg['db'], cfg['user'], cfg['password'] = args.db, args.user, args.password
    cfg['manifest'] = args.manifest
    return cfg


