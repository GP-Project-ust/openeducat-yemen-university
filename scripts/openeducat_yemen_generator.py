def recon(odoo, rep):
    """فحص النماذج المتاحة قبل أي كتابة."""
    op_models = odoo.search_read('ir.model', [('model', '=like', 'op.%')],
                                 ['model', 'name'])
    have = {m['model'] for m in op_models}
    rep.log('نماذج OpenEduCat المتاحة: %d نموذجاً' % len(have))
    runnable = {}
    for ph, models in PHASE_MODELS.items():
        missing = [m for m in models if m not in have]
        if missing:
            rep.warn('المرحلة %d ستتخطى — نماذج غير مثبتة: %s'
                     % (ph, '، '.join(missing)))
        else:
            runnable[ph] = True
    if not runnable:
        raise SystemExit('لا توجد نماذج OpenEduCat — ثبّت وحدات openeducat_core '
                         'و openeducat_admission و openeducat_exam و openeducat_fees')
    return set(runnable.keys())


def main():
    args = build_parser().parse_args()
    cfg = merge_config(args)
    cfg['preset'] = args.preset
    rng = random.Random(cfg['seed'])
    rep = Reporter()
    odoo = Odoo(cfg, rep)
    odoo.login()
    manifest = Manifest(cfg['manifest'])

    if args.purge:
        if not args.yes:
            answer = input('سيتم حذف كل سجلات هذا السكريبت نهائياً. متابعة؟ (نعم/لا) ')
            if answer.strip() not in ('نعم', 'y', 'yes'):
                print('أُلغي الحذف.')
                return
        run_purge(odoo, rep, manifest)
        rep.save('تم الحذف العكسي بنجاح')
        return

    available = recon(odoo, rep)
    if args.only_phases:
        wanted = {int(x) for x in args.only_phases.split(',') if x.strip()}
        available &= wanted
    if 6 in available and args.no_exams:
        available.discard(6)
    plan = build_plan(cfg, rng)
    print_plan(cfg, plan, rep)
    if args.dry_run:
        rep.log('وضع dry-run: لم تُكتب أي بيانات — هذه كانت الخطة فقط')
        rep.save('dry-run')
        return
    if not args.yes:
        answer = input('\nهل تريد المتابعة وبدء التوليد؟ (نعم/لا) ')
        if answer.strip() not in ('نعم', 'y', 'yes'):
            print('أُلغي التشغيل بأمان — لم يُكتب شيء.')
            return

    names = NameFactory(rng)
    counters = {}
    results = {}
    for ph in sorted(available):
        func = PHASE_FUNCS[ph]
        t0 = time.time()
        rep.log('')
        try:
            results[ph] = func(odoo, rep, manifest, plan, cfg, rng, names,
                               counters)
        except SystemExit:
            raise
        except Exception as exc:  # عزل المراحل: إخفاق مرحلة لا يوقف البقية
            rep.warn('المرحلة %d توقفت بخطأ: %s' % (ph, str(exc)[:300]))
            import traceback
            traceback.print_exc()
        rep.log('   زمن المرحلة %d: %.1f ثانية' % (ph, time.time() - t0))

    summary = [
        '=' * 62,
        'اكتمل التوليد في %.1f دقيقة' % ((time.time() - rep.t0) / 60),
        'عدد التحذيرات: %d' % len(rep.warnings),
        'ملف الحذف العكسي: %s' % cfg['manifest'],
        'للحذف لاحقاً: python3 %s --purge --yes' % sys.argv[0],
    ]
    path = rep.save('\n'.join(summary))
    print('\n'.join(summary))
    print('تقرير التوليد: %s' % path)


if __name__ == '__main__':
    main()
