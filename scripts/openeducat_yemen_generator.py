def _country_yemen(odoo, rep):
    got = odoo.search_read('res.country', [('code', '=', 'YE')], ['id'],
                           limit=1)
    if got:
        return got[0]['id']
    got = odoo.search_read('res.country', [('name', 'ilike', 'Yemen')],
                           ['id'], limit=1)
    if got:
        return got[0]['id']
    rep.warn('لم يُعثر على اليمن في دول النظام — ستتخطى حقول الجنسية')
    return None


