class TimeoutTransport(xmlrpc.client.Transport):
    def __init__(self, timeout):
        super().__init__()
        self._timeout = timeout

    def make_connection(self, host):
        conn = super().make_connection(host)
        conn.timeout = self._timeout
        return conn


class Odoo:
    """غلاف رقيق وآمن لواجهة XML-RPC الثانية (/xmlrpc/2)."""

    # سياق يوقف إشعارات/تتبع البريد أثناء التوليد الجماعي — نفس ما يستخدمه
    # مستورد أودو الرسمي. يسرّع الإنشاء كثيراً ويمنع آلاف سجلات chatter.
    QUIET_CTX = {
        'tracking_disable': True,
        'mail_create_nolog': True,
        'mail_create_nosubscribe': True,
        'mail_notrack': True,
    }

    def __init__(self, cfg, rep):
        self.cfg = cfg
        self.rep = rep
        t = TimeoutTransport(cfg['request_timeout'])
        self.common = xmlrpc.client.ServerProxy(
            '%s/xmlrpc/2/common' % cfg['url'], transport=t, allow_none=True)
        self.models = xmlrpc.client.ServerProxy(
            '%s/xmlrpc/2/object' % cfg['url'], transport=t, allow_none=True)
        self.uid = None

    def login(self):
        self.uid = self.common.authenticate(
            self.cfg['db'], self.cfg['user'], self.cfg['password'], {})
        if not self.uid:
            raise SystemExit(
                'فشل تسجيل الدخول — تحقق من الرابط/القاعدة/المستخدم/كلمة المرور')
        self.rep.log('تم الاتصال بخادم أودو: %s (قاعدة: %s، المستخدم uid=%s)'
                     % (self.cfg['url'], self.cfg['db'], self.uid))
        return self.uid

    def call(self, model, method, *args, **kw):
        """استدعاء مع إعادة محاولة للأخطاء العابرة فقط (شبكة/مهلة).

        الأخطاء المنطقية Fault من الخادم (قيود، تحقق) لا تُعاد محاولتها —
        إعادة محاولتها مضيعة للوقت لأن النتيجة واحدة. الوسائط الإضافية
        للإنشاء/الكتابة تُنفذ مع سياق يوقف إشعارات البريد.
        """
        if method in ('create', 'write'):
            kw = dict(kw)
            ctx = dict(kw.get('context') or {})
            for k, v in self.QUIET_CTX.items():
                ctx.setdefault(k, v)
            kw['context'] = ctx
        last_err = None
        for attempt in range(3):
            try:
                return self.models.execute_kw(
                    self.cfg['db'], self.uid, self.cfg['password'],
                    model, method, list(args), kw)
            except xmlrpc.client.Fault:
                raise
            except (xmlrpc.client.ProtocolError, xmlrpc.client.ResponseError,
                    ConnectionError, TimeoutError, OSError) as e:
                last_err = e
                time.sleep(2 * (attempt + 1))
        raise last_err

    # ---- اختصارات ----
    def search(self, model, domain, limit=None):
        kw = {}
        if limit:
            kw['limit'] = limit
        return self.call(model, 'search', domain, **kw)

    def search_read(self, model, domain, fields, limit=None):
        kw = {'fields': fields}
        if limit:
            kw['limit'] = limit
        return self.call(model, 'search_read', domain, **kw)

    def create(self, model, vals_list):
        if isinstance(vals_list, dict):
            vals_list = [vals_list]
        if not vals_list:
            return []
        return self.call(model, 'create', vals_list)

    def write(self, model, ids, vals):
        if not ids:
            return True
        return self.call(model, 'write', ids, vals)

    def fields_get(self, model):
        return self.call(model, 'fields_get', [], attributes=['type', 'required'])

    def model_exists(self, model):
        return bool(self.search(
            'ir.model', [('model', '=', model)], limit=1))


