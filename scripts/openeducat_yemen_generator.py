def _create_indexed(odoo, rep, manifest, model, vals_list):
    """إنشاء مع تتبع المحاذاة: يعيد أزواج (الفهرس، المعرف) للناجحين فقط."""
    pairs = []
    batch = odoo.cfg['rpc_batch']
    for i in range(0, len(vals_list), batch):
        chunk = vals_list[i:i + batch]
        base = i
        try:
            got = odoo.create(model, chunk)
            if not isinstance(got, list):
                got = [got]
            for j, rid in enumerate(got):
                pairs.append((base + j, rid))
        except xmlrpc.client.Fault as e:
            rep.warn('دفعة %s فشلت (%s) — إنشاء فردي' % (model, str(e)[:140]))
            for j, vals in enumerate(chunk):
                try:
                    rid = odoo.create(model, vals)
                    pairs.append((base + j, rid if not isinstance(rid, list)
                                  else rid[0]))
                except xmlrpc.client.Fault:
                    continue
    manifest.add(model, [rid for _, rid in pairs])
    return pairs


