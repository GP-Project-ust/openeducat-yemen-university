def _load_maps(odoo, plan, counters):
    """تحميل خرائط المعرّفات من القاعدة (لجولات منفصلة أو مستأنفة)."""
    if 'years' not in counters:
        ymap = {r['name']: r['id'] for r in odoo.search_read(
            'op.academic.year',
            [('name', 'in', [y['name'] for y in plan['years']])], ['id'])}
        counters['years'] = ymap
    if 'courses' not in counters:
        counters['courses'] = {r['code']: r['id'] for r in odoo.search_read(
            'op.course', [('code', 'in', [p['code'] for p in PROGRAMS])],
            ['code'])}
    if 'batches' not in counters:
        counters['batches'] = {r['code']: r['id'] for r in odoo.search_read(
            'op.batch', [('code', 'in', [b['code'] for b in plan['batches']])],
            ['code'])}
    if 'departments' not in counters:
        dep_codes = ['F-%s' % c for c, _n in FACULTIES] + \
                    ['D-%s' % p['code'] for p in PROGRAMS]
        counters['departments'] = {
            r['code']: r['id'] for r in read_all(
                odoo, 'op.department', [('code', 'in', dep_codes)], ['code'])}
    if 'subjects' not in counters:
        codes = []
        for p in PROGRAMS:
            year_lists = {1: _COMMON[p['f']]}
            year_lists.update(p['years_subj'])
            for ynum in sorted(year_lists):
                for i in range(len(year_lists[ynum])):
                    codes.append('%s-Y%d-%d' % (p['code'], ynum, i + 1))
        counters['subjects'] = {r['code']: r['id'] for r in read_all(
            odoo, 'op.subject', [('code', 'in', codes)], ['code'])}


def _load_students(odoo, counters):
    """قراءة كل طلابنا (بادئة YU) مع دفعاتهم من القاعدة."""
    bmap = counters['batches']
    students = read_all(odoo, 'op.student', [('gr_no', '=like', 'YU%')],
                        ['gr_no', 'name', 'first_name', 'middle_name',
                         'last_name', 'birth_date', 'gender', 'email',
                         'mobile'])
    enr = read_all(odoo, 'op.student.course', [], ['student_id', 'batch_id'])
    batch_of = {}
    for e in enr:
        if e['student_id']:
            batch_of[e['student_id'][0]] = (
                e['batch_id'][0] if e['batch_id'] else None)
    rev_batch = {v: k for k, v in bmap.items()}
    out = []
    for s in students:
        bcode = rev_batch.get(batch_of.get(s['id']))
        if bcode:
            out.append(dict(sid=s['id'], batch=bcode, **{
                k: s.get(k) for k in ('gr_no', 'name', 'first_name',
                                      'middle_name', 'last_name', 'birth_date',
                                      'gender', 'email', 'mobile')}))
    return out


def read_all(odoo, model, domain, fields, page=1000):
    """قراءة كل السجلات بترقيم صفحات آمن."""
    out, offset = [], 0
    while True:
        page_rows = odoo.models.execute_kw(
            odoo.cfg['db'], odoo.uid, odoo.cfg['password'],
            model, 'search_read', [domain],
            {'fields': fields, 'limit': page, 'offset': offset})
        out.extend(page_rows)
        if len(page_rows) < page:
            break
        offset += page
    return out


