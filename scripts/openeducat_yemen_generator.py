class Reporter:
    def __init__(self, path='generation_report.txt'):
        self.path = path
        self.lines = []
        self.t0 = time.time()
        self.warnings = []

    def log(self, msg):
        stamp = time.strftime('%H:%M:%S')
        line = '[%s] %s' % (stamp, msg)
        print(line)
        self.lines.append(line)

    def warn(self, msg):
        self.warnings.append(msg)
        self.log('⚠ تنبيه: ' + msg)

    def save(self, summary):
        with open(self.path, 'w', encoding='utf-8') as fh:
            fh.write('\n'.join(self.lines + ['', '=' * 60, summary]))
        return self.path


